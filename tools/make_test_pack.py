#!/usr/bin/env python3
"""Generate the placeholder asset pack used by tests and CI.

The pack contains no retail artwork. It declares every sprite, font and GUI
atlas the engine and the project's own missions reference, using flat
placeholder colours. Declarations use the retail Lua layout, so tests also
exercise the retail declaration importer.

    python3 tools/make_test_pack.py --output build/packs/test
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw

DIRECTIONS = range(8)
WORKER_ACTIONS = ("run", "bag", "srepair", "gather", "wood", "pick", "tap", "pet", "call", "repair")

# name: (world width, world height, frame count). Pivots sit near the base.
STATIC = {
    "base0": (123, 106, 1), "build_place": (96, 56, 1), "icon_head": (20, 20, 1),
    "target": (24, 24, 1), "progress": (66, 12, 2), "worker_shadow": (30, 12, 1),
    "man_shadow": (30, 12, 1), "water0": (64, 32, 4), "butterfly": (16, 12, 6),
    "bar_tree00": (110, 64, 1), "bar_stone00": (64, 46, 1), "bar_stone_big00": (92, 70, 1),
    "bridge_wood00": (90, 60, 4), "bridge_wood01": (90, 60, 4), "bridge_auto00": (110, 70, 4),
    "bridge_auto01": (110, 70, 4), "broken_road0": (80, 44, 1), "fog_high": (128, 96, 1),
    "sawmill0": (120, 100, 1), "sawmill0_br": (120, 100, 1), "burger0": (110, 96, 1),
    "burger0_br": (110, 96, 1), "house0": (104, 100, 1), "house0_br": (104, 100, 1),
    "gas0": (110, 104, 1), "gas0_br": (110, 104, 1), "food": (36, 28, 1), "food_big": (46, 34, 1),
    "wood": (40, 26, 1), "wood_big": (50, 32, 1), "money": (34, 26, 1), "money_big": (44, 32, 1),
    "gas": (30, 30, 1), "gas_big": (40, 36, 1), "tap": (36, 40, 2), "seaport": (120, 70, 1),
    "seaport_br": (120, 70, 1), "garage0": (110, 90, 1), "boat_fish_idle": (40, 30, 1),
    "boat_fish_action0": (60, 40, 4), "worker_wait0": (30, 46, 4), "man_idle0": (28, 44, 4),
    "wman_idle0": (28, 44, 4), "bird": (24, 16, 4), "cloud": (180, 90, 1),
}


def sprites():
    table = dict(STATIC)
    for action in WORKER_ACTIONS:
        for d in DIRECTIONS:
            table[f"worker_{action}{d}"] = (32, 48, 4)
    for d in DIRECTIONS:
        table[f"man_run{d}"] = (30, 46, 4)
    for d in range(24):
        table[f"boat{d}"] = (60, 40, 1)
    for d in range(16):
        table[f"offroad{d}"] = (70, 50, 1)
    for species in ("cat", "dog"):
        for variant in range(3):
            table[f"{species}{variant}_idle0"] = (30, 22, 4)
            for d in DIRECTIONS:
                table[f"{species}{variant}_walk{d}"] = (30, 22, 4)
                table[f"{species}{variant}_run{d}"] = (30, 22, 4)
    return table


FONTS = (("CambriaBold30W", "Cambria", 30), ("CambriaBold30B", "Cambria", 30),
         ("CalibriRegular22N", "Calibri", 22), ("CalibriBold20W", "Calibri", 20),
         ("CalibriBold20G", "Calibri", 20))


def write_sprites(folder):
    table = sprites()
    cell, columns = 32, 32
    size = cell * columns
    image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    lines = ["-- Placeholder sprites generated by tools/make_test_pack.py"]
    for index, (name, (w, h, count)) in enumerate(sorted(table.items())):
        x, y = (index % columns) * cell, (index // columns) * cell
        hue = (index * 67) % 255
        draw.rectangle((x + 1, y + 1, x + cell - 2, y + cell - 2), fill=(hue, 255 - hue, 120, 255))
        u, v, cu, cv = x / size, 1 - (y + cell) / size, cell / size, cell / size
        frame = f"  {{ dx={w / 2:g}, dy={h * .15:g}, u={u:.8f}, v={v:.8f}, cu={cu:.8f}, cv={cv:.8f}, w={w}, h={h} }},"
        lines += [f"texinfo = createTextureInfoEx('{name}')", "frames =", "{"]
        lines += [frame] * count + ["}", "addTextureInfoExNodes(texinfo, 'test-sprites', frames, 15)", ""]
    folder.mkdir(parents=True, exist_ok=True)
    image.save(folder / "test-sprites.png")
    (folder / "test.lua").write_text("\n".join(lines))
    return len(table)


def write_fonts(folder):
    folder.mkdir(parents=True, exist_ok=True)
    Image.new("RGBA", (256, 256), (255, 255, 255, 255)).save(folder / "test-font.png")
    blocks = []
    for name, family, size in FONTS:
        glyphs = []
        for code in range(32, 127):
            ch = chr(code).replace("\\", "\\\\").replace("'", "\\'")
            w = 0 if code == 32 else size // 2
            glyphs.append(f"  {{ ch='{ch}', x=0, y=0, w={w}, h={size}, bX=0, bY={size}, aX={size // 2}, aY=0 }},")
        blocks.append("\n".join([f"font = createFont('{name}')",
                                 f"initFont(font, '{family}', 'Bold', {size})",
                                 "setFontTexture(font, 'test-font', 256, 256)",
                                 "chars =", "{", *glyphs, "}", "fillFont(font, chars)", "font = nil"]))
    half = (len(blocks) + 1) // 2
    (folder / "CambriaBold30W.lua").write_text("\n\n".join(blocks[:half]) + "\n")
    (folder / "CambriaBold30B.lua").write_text("\n\n".join(blocks[half:]) + "\n")


def write_images(root):
    gui = root / "texture/gui"
    gui.mkdir(parents=True, exist_ok=True)
    for name in ("gui00.png", "gui01.png"):
        Image.new("RGBA", (1024, 1024), (40, 70, 90, 220)).save(gui / name)
    Image.new("RGBA", (512, 512), (90, 220, 120, 160)).save(gui / "highlight.png")
    static = root / "texture/static"
    static.mkdir(parents=True, exist_ok=True)
    Image.new("RGBA", (256, 128), (255, 140, 40, 200)).save(static / "part_fire.png")
    Image.new("RGBA", (64, 64), (120, 120, 120, 120)).save(static / "part_smoke.png")
    Image.new("RGBA", (128, 96), (230, 230, 230, 140)).save(static / "part_fog_high.png")
    back = root / "texture/back"
    back.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", (1672, 941), (72, 110, 64)).save(back / "103_0.jpg", quality=60)
    Image.new("L", (1672, 941), 255).save(back / "103_0.alpha", format="JPEG", quality=60)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root = args.output.resolve()
    count = write_sprites(root / "texture/lazy")
    write_fonts(root / "font/en")
    write_images(root)
    print(f"Test pack: {count} placeholder sprites, {len(FONTS)} fonts, GUI atlases -> {root}")


if __name__ == "__main__":
    main()
